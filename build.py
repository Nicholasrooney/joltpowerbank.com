import hashlib
def _v(path):
    with open(os.path.join(HERE, path), "rb") as f:
        return hashlib.sha1(f.read()).hexdigest()[:8]
CSS_V, JS_V = _v("assets/style.css"), _v("assets/site.js")

def load_testimonials():
    p = os.path.join(HERE, "content", "testimonials.json")
